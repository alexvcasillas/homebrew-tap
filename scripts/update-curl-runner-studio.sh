#!/usr/bin/env bash
# Regenerate Casks/curl-runner-studio.rb for the latest curl-runner GitHub
# release, hashing the curl-runner-studio-<version>.dmg attached to it.
# The dmg is attached by a job that runs after the CLI assets, so a release
# without one is not an error: exits 0 with changed=false and leaves the cask
# alone. Also exits 0 without changes when the cask is already at that version
# (FORCE=1 rewrites it anyway). On GitHub Actions, writes `version=<v>` and
# `changed=<true|false>` to $GITHUB_OUTPUT.
# Usage: scripts/update-curl-runner-studio.sh [version]   (default: latest release)
set -euo pipefail

REPO="alexvcasillas/curl-runner"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CASK="${CASK:-$ROOT/Casks/curl-runner-studio.rb}"

output() { [ -n "${GITHUB_OUTPUT:-}" ] && echo "$1" >> "$GITHUB_OUTPUT" || true; }
api() {
  curl -fsSL -H "Accept: application/vnd.github+json" \
    ${GITHUB_TOKEN:+-H "Authorization: Bearer $GITHUB_TOKEN"} "$1"
}

if [ -n "${1:-}" ]; then
  version="$1"
else
  tag="$(api "https://api.github.com/repos/$REPO/releases/latest" | jq -r .tag_name)"
  version="${tag##*@}"
fi
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "error: unexpected version '$version'" >&2; exit 1; }
output "version=$version"

current="$(sed -n 's/^  version "\(.*\)"$/\1/p' "$CASK" 2>/dev/null || true)"
if [ "$current" = "$version" ] && [ "${FORCE:-}" != 1 ]; then
  echo "curl-runner studio $version: cask already up to date"
  output "changed=false"
  exit 0
fi

dmg="curl-runner-studio-$version.dmg"
assets="$(api "https://api.github.com/repos/$REPO/releases/tags/%40curl-runner%2Fcli%40$version" \
  | jq -r '.assets[].name')"
if ! grep -qxF "$dmg" <<<"$assets"; then
  echo "curl-runner studio $version: release has no $dmg yet, skipping"
  output "changed=false"
  exit 0
fi

base="https://github.com/$REPO/releases/download/@curl-runner/cli@$version"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
curl -fsSL -o "$tmp/$dmg" "$base/$dmg"
sha="$(shasum -a 256 "$tmp/$dmg" | awk '{ print $1 }')"
[[ "$sha" =~ ^[0-9a-f]{64}$ ]] || { echo "error: could not hash $dmg" >&2; exit 1; }

mkdir -p "$(dirname "$CASK")"
cat > "$CASK" <<EOT
# Generated by scripts/update-curl-runner-studio.sh from the curl-runner
# release. Do not edit by hand.
cask "curl-runner-studio" do
  version "$version"
  sha256 "$sha"

  url "$base/curl-runner-studio-#{version}.dmg"
  name "curl-runner studio"
  desc "Desktop app for running HTTP request suites defined in YAML"
  homepage "https://www.curl-runner.com/"

  depends_on macos: :monterey

  app "curl-runner studio.app"

  zap trash: "~/Library/Application Support/curl-runner-studio"
end
EOT
echo "curl-runner studio: cask ${current:-<none>} -> $version"
output "changed=true"
