#!/usr/bin/env bash
# Regenerate Formula/curl-runner.rb for the latest curl-runner GitHub release,
# using the checksums published in that release's SHA256SUMS.txt.
# Exits 0 without changes when the formula is already at that version
# (FORCE=1 rewrites it anyway). On GitHub Actions, writes `version=<v>` and
# `changed=<true|false>` to $GITHUB_OUTPUT.
# Usage: scripts/update-curl-runner.sh [version]   (default: latest release)
set -euo pipefail

REPO="alexvcasillas/curl-runner"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FORMULA="$ROOT/Formula/curl-runner.rb"

output() { [ -n "${GITHUB_OUTPUT:-}" ] && echo "$1" >> "$GITHUB_OUTPUT" || true; }

if [ -n "${1:-}" ]; then
  version="$1"
else
  tag="$(curl -fsSL -H "Accept: application/vnd.github+json" \
    ${GITHUB_TOKEN:+-H "Authorization: Bearer $GITHUB_TOKEN"} \
    "https://api.github.com/repos/$REPO/releases/latest" | jq -r .tag_name)"
  version="${tag##*@}"
fi
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "error: unexpected version '$version'" >&2; exit 1; }
output "version=$version"

current="$(sed -n 's/^  version "\(.*\)"$/\1/p' "$FORMULA" 2>/dev/null || true)"
if [ "$current" = "$version" ] && [ "${FORCE:-}" != 1 ]; then
  echo "curl-runner $version: formula already up to date"
  output "changed=false"
  exit 0
fi

base="https://github.com/$REPO/releases/download/@curl-runner/cli@$version"
sums="$(curl -fsSL "$base/SHA256SUMS.txt")"
sha() {
  local s
  s="$(awk -v f="curl-runner-cli-$version-$1.tar.gz" '$2 == f { print $1 }' <<<"$sums")"
  [[ "$s" =~ ^[0-9a-f]{64}$ ]] || { echo "error: no checksum for $1 in SHA256SUMS.txt" >&2; exit 1; }
  echo "$s"
}
darwin_arm64="$(sha darwin-arm64)"
darwin_x64="$(sha darwin-x64)"
linux_arm64="$(sha linux-arm64)"
linux_x64="$(sha linux-x64)"

mkdir -p "$(dirname "$FORMULA")"
cat > "$FORMULA" <<EOF
# Generated by scripts/update-curl-runner.sh from the curl-runner release
# checksums. Do not edit by hand.
class CurlRunner < Formula
  desc "Run HTTP request suites defined in YAML, on libcurl"
  homepage "https://www.curl-runner.com"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/curl-runner-cli-$version-darwin-arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/curl-runner-cli-$version-darwin-x64.tar.gz"
      sha256 "$darwin_x64"
    end
  end

  on_linux do
    on_arm do
      url "$base/curl-runner-cli-$version-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/curl-runner-cli-$version-linux-x64.tar.gz"
      sha256 "$linux_x64"
    end
  end

  def install
    # Each archive holds one binary named curl-runner-<platform>.
    bin.install Dir["curl-runner-*"].first => "curl-runner"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/curl-runner --version").strip
    (testpath/"dry.yaml").write <<~YAML
      request:
        url: https://example.com
    YAML
    assert_match "curl", shell_output("#{bin}/curl-runner dry.yaml --dry-run")
  end
end
EOF
echo "curl-runner: formula ${current:-<none>} -> $version"
output "changed=true"
